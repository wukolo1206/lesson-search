for sheet in GRADE_SHEETS:
    df = pd.read_excel(EXCEL_PATH, sheet_name=sheet)
    
    # 找出這個年級的衝突題目
    sheet_conflicts = [c for c in CONFLICT_CASES if c[0] == sheet]
    
    for (grade, q_num, title, labeled, predicted, reason) in sheet_conflicts:
        # 找出這篇文章的所有題目（共享同一份完整文章）
        article_rows = df[df['文本標題'] == title]
        if len(article_rows) == 0:
            continue
        
        # 找文章全文（取第一筆有文章內容的）
        article_text = ""
        for _, ar in article_rows.iterrows():
            if not pd.isna(ar.get('文章全文', '')) and len(str(ar.get('文章全文', ''))) > 10:
                article_text = str(ar['文章全文'])
                break
        
        # 找到這道特定題目
        target_row = None
        for _, ar in article_rows.iterrows():
            q_text = str(ar.get('完整題目', ''))
            if q_text.startswith(q_num + ".") or q_text.startswith(str(q_num) + "."):
                target_row = ar
                break
        
        if target_row is None:
            # 如果找不到精確題號，取第一筆
            target_row = article_rows.iloc[0]
        
        # 輸出成 txt 檔
        safe_title = title.replace('/', '').replace('\\', '').replace('*', '').replace('?', '')[:15]
        filename = os.path.join(OUTPUT_DIR, f"{grade}_Q{q_num}_{safe_title}.txt")
        
